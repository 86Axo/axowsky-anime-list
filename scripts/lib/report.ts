import type { AnimeEntry } from '../../src/lib/types';
import type { MatchRecord } from '../sync';

const cell = (s: string): string => s.replace(/\|/g, '\\|');
const malLink = (id: number, title: string): string => `[${cell(title)}](https://myanimelist.net/anime/${id})`;

/**
 * data/unmatched.md: every title that needs a human look.
 * Deterministic (no timestamps) so it only shows up in a commit when something changed.
 */
export function renderReport(entries: AnimeEntry[], records: Map<string, MatchRecord>, pending: string[]): string {
  const count = (c: string) => entries.filter((e) => e.match.confidence === c).length;
  const fromAniList = entries.filter((e) => e.mal?.source === 'anilist').length;
  const pendingSet = new Set(pending);
  const low = entries.filter((e) => e.match.confidence === 'low');
  const none = entries.filter((e) => e.match.confidence === 'none' && !pendingSet.has(e.title));
  const waiting = entries.filter((e) => e.match.confidence === 'none' && pendingSet.has(e.title));

  // Two list rows that resolved to the same MAL entry are almost always a wrong match.
  const byMal = new Map<number, AnimeEntry[]>();
  for (const e of entries) {
    if (!e.mal) continue;
    byMal.set(e.mal.id, [...(byMal.get(e.mal.id) ?? []), e]);
  }
  const shared = [...byMal.values()].filter((group) => group.length > 1);

  const lines: string[] = [
    '# MAL match report',
    '',
    'Generated by `npm run sync`. To fix a wrong or missing match, add the OglądajAnime slug (or exact title)',
    'and the right MyAnimeList id to `data/overrides.json`, then run the sync again.',
    '',
    '| Result | Count |',
    '| --- | ---: |',
    `| Exact title match | ${count('exact')} |`,
    `| High confidence | ${count('high')} |`,
    `| Low confidence | ${low.length} |`,
    `| Manual override | ${count('override')} |`,
    `| Unmatched | ${none.length} |`,
    `| Waiting for a source | ${waiting.length} |`,
    `| **Total** | **${entries.length}** |`,
    '',
    ...(fromAniList > 0
      ? [
          `${fromAniList} titles currently use backup data from AniList, because Jikan was unreachable. They are matched by the same rules,`,
          'keep their MAL ids and links, and are replaced by MyAnimeList data on the first run where Jikan answers.',
          'Low-confidence and unmatched titles from AniList are searched again on Jikan at that point.',
          '',
        ]
      : []),
  ];

  lines.push('## Low confidence', '');
  if (low.length === 0) lines.push('None.', '');
  else {
    lines.push('| OA title | Type | OA slug | Matched MAL entry | Similarity | Runner-up |', '| --- | --- | --- | --- | ---: | --- |');
    for (const e of low) {
      const rec = records.get(e.key);
      const runner = rec?.runnerUp ? `${malLink(rec.runnerUp.malId, rec.runnerUp.title)} (${rec.runnerUp.score})` : '';
      const matched = e.mal
        ? `${malLink(e.mal.id, e.mal.title)} · ${e.mal.type ?? '?'}`
        : rec?.malId
          ? `not used, another title already has ${malLink(rec.malId, rec.matchedTitle ?? String(rec.malId))}`
          : '';
      lines.push(`| ${cell(e.title)} | ${e.type} | \`${e.slug ?? ''}\` | ${matched} | ${e.match.score} | ${runner} |`);
    }
    lines.push('');
  }

  lines.push('## Unmatched', '');
  if (none.length === 0) lines.push('None.', '');
  else {
    lines.push('| OA title | Type | OA slug |', '| --- | --- | --- |');
    for (const e of none) lines.push(`| ${cell(e.title)} | ${e.type} | \`${e.slug ?? ''}\` |`);
    lines.push('');
  }

  if (waiting.length > 0) {
    lines.push('## Waiting for a source', '', 'Neither Jikan nor AniList was reachable during the last run. These are looked up on the next run.', '');
    for (const e of waiting) lines.push(`- ${e.title}`);
    lines.push('');
  }

  lines.push('## Same MAL entry matched more than once', '');
  if (shared.length === 0) lines.push('None.', '');
  else {
    for (const group of shared) {
      const mal = group[0]!.mal!;
      lines.push(`- ${malLink(mal.id, mal.title)} ← ${group.map((e) => `"${e.title}" (\`${e.slug ?? e.key}\`)`).join(', ')}`);
    }
    lines.push('');
  }

  return lines.join('\n');
}
